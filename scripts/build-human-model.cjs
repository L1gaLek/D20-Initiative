// Reproducible CC0 asset conversion. Run: node scripts/build-human-model.cjs <source-dir>
// Source URLs, pinned revision and license: assets/models/human/README.md.
const fs=require('node:fs');
const path=require('node:path');
const {createHash}=require('node:crypto');
const source=path.resolve(process.argv[2]||'human-source');
const read=file=>fs.readFileSync(path.join(source,file),'utf8');
const sex=process.argv[3]==='female'?'female':'male';
const vertices=[],faces=[];let group='';
for(const line of read('base.obj').split(/\r?\n/)){
  if(line.startsWith('v '))vertices.push(line.trim().split(/\s+/).slice(1).map(Number));
  if(line.startsWith('g '))group=line.slice(2).trim();
  if(line.startsWith('f ')&&group==='body')faces.push(line.trim().split(/\s+/).slice(1).map(v=>Number(v.split('/')[0])-1));
}
const targets=sex==='female'?[['caucasian-female-young.target',1],['universal-female-young-averagemuscle-averageweight.target',1]]:[['caucasian-male-young.target',1],['universal-male-young-maxmuscle-averageweight.target',.38]];
for(const [file,strength] of targets){
  for(const line of read(file).split(/\r?\n/))if(/^\d/.test(line)){
    const [index,...delta]=line.trim().split(/\s+/).map(Number);
    delta.forEach((v,a)=>vertices[index][a]+=v*strength);
  }
}
const rig=JSON.parse(read('default.mhskel')),weights=JSON.parse(read('default_weights.mhw')).weights;
const names=Object.keys(rig.bones),used=[...new Set(faces.flat())].sort((a,b)=>a-b),remap=new Map(used.map((v,i)=>[v,i]));
const minY=Math.min(...used.map(i=>vertices[i][1])),maxY=Math.max(...used.map(i=>vertices[i][1]));
const scale=1.56/(maxY-minY);
const transform=v=>[v[0]*scale,(v[1]-minY)*scale+.116,v[2]*scale];
const joint=name=>transform(rig.joints[name].reduce((a,i)=>a.map((v,k)=>v+vertices[i][k]/rig.joints[name].length),[0,0,0]));
const bones=names.map(name=>({name,parent:names.indexOf(rig.bones[name].parent),head:joint(rig.bones[name].head),tail:joint(rig.bones[name].tail)}));
const influences=vertices.map(()=>[]);
for(const [name,entries] of Object.entries(weights))for(const [v,w] of entries)if(w>0)influences[v].push([names.indexOf(name),w]);
const positions=new Float32Array(used.flatMap(i=>transform(vertices[i]))),skinIndices=new Uint8Array(used.length*4),skinWeights=new Uint8Array(used.length*4);
used.forEach((v,i)=>{
  const list=influences[v].filter(w=>w[0]>=0).sort((a,b)=>b[1]-a[1]).slice(0,4);if(!list.length)list.push([names.indexOf('root'),1]);
  const sum=list.reduce((s,v)=>s+v[1],0);let assigned=0;
  list.forEach(([bone,w],j)=>{skinIndices[i*4+j]=bone;const value=j===list.length-1?255-assigned:Math.round(w/sum*255);skinWeights[i*4+j]=value;assigned+=value;});
});
const triangles=[];for(const face of faces)for(let j=1;j<face.length-1;j++)triangles.push(remap.get(face[0]),remap.get(face[j]),remap.get(face[j+1]));
const encode=a=>Buffer.from(a.buffer,a.byteOffset,a.byteLength).toString('base64');
const destination=path.resolve(__dirname,'../assets/models/human');fs.mkdirSync(destination,{recursive:true});
const output={positions:encode(positions),skinIndices:encode(skinIndices),skinWeights:encode(skinWeights),indices:encode(new Uint16Array(triangles)),bones};
fs.writeFileSync(path.join(destination,sex+'.mjs'),'// Generated by scripts/build-human-model.cjs; MakeHuman CC0. See README.md.\nexport default '+JSON.stringify(output)+';\n');
const hashes=Object.fromEntries(['base.obj',...targets.map(([f])=>f),'default.mhskel','default_weights.mhw'].map(f=>[f,createHash('sha256').update(read(f)).digest('hex')]));
fs.writeFileSync(path.join(destination,sex==='female'?'female-source-hashes.json':'source-hashes.json'),JSON.stringify(hashes,null,2)+'\n');
fs.copyFileSync(path.join(source,'LICENSE.ASSETS.md'),path.join(destination,'CC0.txt'));
console.log(JSON.stringify({sex,vertices:used.length,triangles:triangles.length/3,bones:bones.length,bytes:fs.statSync(path.join(destination,sex+'.mjs')).size}));
